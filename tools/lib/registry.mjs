// Shared registry generation for the CLI and staged library installation.
export function registryFiles(metas, categories, readme) {
  const order = new Map(categories.map((c, i) => [c.id, i]));
  const rank = id => order.get(id.split('/')[0]) ?? 99;
  metas = [...metas].sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
  const ids = metas.map(m => m.id), ident = id => id.replace(/[^a-z0-9]+/gi, '_');
  const index = ["// Generated by tools/index.mjs: every effect, by id. Don't edit; run `node tools/index.mjs`.", '',
    ...ids.map(id => `import * as ${ident(id)} from "./${id}.js";`), '', 'export { categories } from "./categories.js";', '',
    'export const effects = {', ...ids.map(id => `  "${id}": ${ident(id)},`), '};', ''].join('\n');
  const md = ['# Catalog', '', `${ids.length} effects in ${categories.filter(c => metas.some(m => m.id.startsWith(c.id + '/'))).length} categories. Every one is a file in`,
    '`src/fx/<category>/<name>.js`; render any of them with `node tools/render.mjs <id> --gif`.', ''];
  for (const c of categories) {
    const list = metas.filter(m => m.id.startsWith(c.id + '/')); if (!list.length) continue;
    md.push(`## ${c.name}`, '', `${c.blurb}.`, '', '| effect | id | | size | what it does |', '|---|---|---|---|---|');
    for (const m of list) md.push(`| ${m.name} | \`${m.id}\` | ${m.loop ? 'loop' : 'one-shot'} ${+m.duration.toFixed(2)}s | ${m.size[0]}×${m.size[1]} | ${m.desc.replace(/\|/g, '\\|')} |`);
    md.push('');
  }
  const rows = categories.map(c => [c, metas.filter(m => m.id.startsWith(c.id + '/'))]).filter(([, list]) => list.length)
    .map(([c, list]) => `| **${c.name}** | ${list.length} | ${list.slice(0, 6).map(m => m.name.toLowerCase()).join(', ')}${list.length > 6 ? '…' : ''} |`);
  const table = ['| category | effects | some of them |', '|---|---|---|', ...rows].join('\n');
  return { 'src/fx/index.js': index, 'docs/CATALOG.md': md.join('\n'), 'README.md': readme
    .replace(/<!-- count -->[\s\S]*?<!-- \/count -->/, `<!-- count -->${ids.length}<!-- /count -->`)
    .replace(/<!-- catalog -->[\s\S]*?<!-- \/catalog -->/, `<!-- catalog -->\n${table}\n<!-- /catalog -->`) };
}
